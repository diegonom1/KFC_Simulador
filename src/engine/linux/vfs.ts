export type Usuario = 'root' | 'sysadmin' | 'tienda'

export function dueñoDe(ruta: string): Usuario {
  if (ruta.startsWith('/home/sysadmin') || ruta.startsWith('/ph')) return 'sysadmin'
  if (ruta.startsWith('/home/tienda')) return 'tienda'
  return 'root'
}

export function puedeLeer(usuario: string, ruta: string): boolean {
  if (usuario === 'root') return true
  if (ruta === '/etc/shadow' || ruta === '/root' || ruta.startsWith('/root/')) return false
  return true
}

export function puedeEscribir(usuario: string, ruta: string): boolean {
  if (usuario === 'root') return true
  if (usuario === 'sysadmin') return ruta.startsWith('/home/sysadmin/') || ruta.startsWith('/ph/') || ruta.startsWith('/tmp/')
  return ruta.startsWith('/home/tienda/') || ruta.startsWith('/tmp/')
}

export function normalizarRuta(cwd: string, arg: string, home: string): string {
  let r = arg
  if (r === '~' || r.startsWith('~/')) r = home + r.slice(1)
  if (!r.startsWith('/')) r = `${cwd === '/' ? '' : cwd}/${r}`
  const partes: string[] = []
  for (const p of r.split('/')) {
    if (!p || p === '.') continue
    if (p === '..') partes.pop()
    else partes.push(p)
  }
  return '/' + partes.join('/')
}

export function padre(ruta: string): string {
  const i = ruta.lastIndexOf('/')
  return i <= 0 ? '/' : ruta.slice(0, i)
}

export function nombreBase(ruta: string): string {
  return ruta.slice(ruta.lastIndexOf('/') + 1)
}

export interface Entrada {
  nombre: string
  ruta: string
  dir: boolean
  exe: boolean
  oculto: boolean
  tam: number
}

export function listar(host: HostLinux, archivos: Record<string, string>, dir: string): Entrada[] {
  const dirs = directorios(host)
  const pref = dir === '/' ? '/' : dir + '/'
  const vistos = new Map<string, Entrada>()
  for (const d of dirs) {
    if (d !== dir && d.startsWith(pref) && !d.slice(pref.length).includes('/')) {
      const nombre = d.slice(pref.length)
      vistos.set(nombre, { nombre, ruta: d, dir: true, exe: false, oculto: nombre.startsWith('.'), tam: 4096 })
    }
  }
  for (const [ruta, cont] of Object.entries(archivos)) {
    if (ruta.startsWith(pref) && !ruta.slice(pref.length).includes('/')) {
      const nombre = ruta.slice(pref.length)
      vistos.set(nombre, { nombre, ruta, dir: false, exe: esBinario(host, ruta), oculto: nombre.startsWith('.'), tam: esBinario(host, ruta) ? 184_320 : new TextEncoder().encode(cont).length })
    }
  }
  return [...vistos.values()].sort((a, b) => a.nombre.localeCompare(b.nombre))
}
