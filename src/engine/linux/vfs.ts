export function directorios(host: HostLinux): Set<string> {
  return new Set([...DIRS_BASE, ...DIRS_HOST[host]])
}

export function esBinario(host: HostLinux, ruta: string): boolean {
  return BINARIOS[host].includes(ruta)
}

